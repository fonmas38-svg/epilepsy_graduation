"""Export a small, auditable evaluation bundle in Colab/Kaggle without EEG transfer.

NPZ keys: y, score, group (test); val_y, val_score, val_group (validation);
train_group (training group IDs). Scores must be generated by the frozen model.
Use non-identifying patient IDs; recording groups do NOT establish patient generalization.
This verifies submitted arrays, not their authenticity or prospective clinical validity.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
from sklearn.metrics import average_precision_score, roc_auc_score


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def checked_vectors(y, score, group):
    y, score, group = np.asarray(y), np.asarray(score), np.asarray(group).astype(str)
    if any(a.ndim != 1 for a in (y, score, group)) or not len(y) or not (len(y) == len(score) == len(group)):
        raise ValueError("Labels, scores and groups must be nonempty aligned vectors")
    if not np.isin(y, [0, 1]).all() or len(np.unique(y)) != 2:
        raise ValueError("Both binary classes must be present")
    if not np.isfinite(score).all() or np.any((score < 0) | (score > 1)):
        raise ValueError("Scores must be finite and between zero and one")
    if np.any(np.char.strip(group) == "") or np.isin(group, ["nan", "None"]).any():
        raise ValueError("Every window needs a valid group ID")
    return y.astype(int), score.astype(float), group


def metrics(y, score, threshold):
    predicted = score >= threshold
    tp = int(np.sum(predicted & (y == 1)))
    fp = int(np.sum(predicted & (y == 0)))
    fn = int(np.sum(~predicted & (y == 1)))
    tn = int(np.sum(~predicted & (y == 0)))
    return {
        "threshold": float(threshold), "tp": tp, "fp": fp, "fn": fn, "tn": tn,
        "sensitivity": tp / (tp + fn), "specificity": tn / (tn + fp),
        "precision": tp / (tp + fp) if tp + fp else None,
        "auc_roc": float(roc_auc_score(y, score)),
        "average_precision": float(average_precision_score(y, score)),
        "brier_score": float(np.mean((score - y) ** 2)),
    }


def evaluate(arrays, min_specificity=0.95, group_kind="patient"):
    if group_kind not in ("patient", "recording") or not 0 < min_specificity <= 1:
        raise ValueError("Invalid evaluation configuration")
    y, score, group = checked_vectors(arrays["y"], arrays["score"], arrays["group"])
    vy, vs, vg = checked_vectors(arrays["val_y"], arrays["val_score"], arrays["val_group"])
    train = np.asarray(arrays["train_group"]).astype(str)
    if train.ndim != 1 or not len(train) or np.any(np.char.strip(train) == ""):
        raise ValueError("Training group IDs are required")
    folds = [set(train), set(vg), set(group)]
    if any(folds[i] & folds[j] for i, j in ((0, 1), (0, 2), (1, 2))):
        raise ValueError("Training, validation and test groups overlap")
    # Select solely on validation scores; never optimize against the test set.
    candidates = np.unique(np.r_[vs, np.nextafter(1.0, np.inf)])
    feasible = []
    for threshold in candidates:
        predicted = vs >= threshold
        specificity = float(np.mean(~predicted[vy == 0]))
        sensitivity = float(np.mean(predicted[vy == 1]))
        if specificity >= min_specificity:
            feasible.append((sensitivity, specificity, float(threshold)))
    _, _, threshold = max(feasible)
    report = metrics(y, score, threshold)
    # Cluster bootstrap preserves within-group correlation. This is not a
    # window-independent binomial interval, nor a seizure-event confidence bound.
    intervals = None
    groups = np.unique(group)
    if len(groups) >= 2:
        rng = np.random.default_rng(42)
        estimates = []
        for _ in range(500):
            ids = np.concatenate([np.flatnonzero(group == g)
                                  for g in rng.choice(groups, len(groups), replace=True)])
            if len(np.unique(y[ids])) < 2:
                continue
            pred = score[ids] >= threshold
            estimates.append([np.mean(pred[y[ids] == 1]), np.mean(~pred[y[ids] == 0])])
        if len(estimates) >= 100:
            bounds = np.percentile(estimates, [2.5, 97.5], axis=0)
            intervals = {"sensitivity": bounds[:, 0].tolist(),
                         "specificity": bounds[:, 1].tolist(),
                         "method": "group_bootstrap_500_seed42"}
    return {
        "clinically_validated": False, "evaluation_scope": "submitted_held_out_window_scores",
        "group_kind": group_kind,
        "group_counts": dict(zip(("train", "validation", "test"), map(len, folds))),
        "validation_selected_threshold": metrics(vy, vs, threshold),
        "test": report, "test_group_bootstrap_95_percent": intervals,
        "event_sensitivity": None, "false_alarms_per_hour": None,
        "lead_time": None,
        "limitations": [
            "Submitted groups and scores require independent provenance verification.",
            "No prospective patient or device validation is established by this report.",
            "Continuous timestamps, seizure events, alarm policy and observation time are required for event metrics.",
            "Recording-level splitting does not prove independence between biological patients.",
        ],
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--predictions", type=Path, required=True)
    parser.add_argument("--weights", type=Path, required=True)
    parser.add_argument("--metadata", type=Path, required=True,
                        help="JSON documenting dataset/version, task, preprocessing, montage and sample rate")
    parser.add_argument("--group-kind", choices=["patient", "recording"], required=True)
    parser.add_argument("--min-specificity", type=float, default=0.95)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    metadata = json.loads(args.metadata.read_text(encoding="utf-8"))
    for key in ("dataset", "dataset_version", "task", "preprocessing", "channel_names", "fs"):
        if not metadata.get(key):
            raise ValueError(f"Missing metadata: {key}")
    with np.load(args.predictions, allow_pickle=False) as arrays:
        report = evaluate(arrays, args.min_specificity, args.group_kind)
    report.update({"weights_sha256": sha256(args.weights),
                   "predictions_sha256": sha256(args.predictions),
                   "metadata_sha256": sha256(args.metadata), "metadata": metadata})
    args.output.write_text(json.dumps(report, indent=2, allow_nan=False), encoding="utf-8")
    print(f"Saved research evaluation to {args.output}; clinical validity remains unverified.")


if __name__ == "__main__":
    main()
